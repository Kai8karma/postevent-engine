def extract_recording_link(template_path: Path) -> str:
    if not template_path.exists():
        return ""
    m = RECORDING_LINK_RE.search(template_path.read_text(encoding="utf-8"))
    return m.group(1) if m else ""


def render_email_preview(props: dict, recording_link: str) -> str:
    first = props.get("firstname", "")
    lines = [f"Hi {first}," if first else "Hi,"]
    headline, body, quote = props.get("takeaway_headline"), props.get("takeaway_body"), props.get("top_quote")
    if headline or body:
        lines.append(" ".join(x for x in (headline, body) if x))
    elif quote:
        lines.append(f'"{quote}"')
    if recording_link:
        lines.append(f"Recording: {recording_link}")
    return "\n\n".join(lines)


def check_approval_gate(m2_dir: Path, force: bool):
    gate_path = m2_dir / "approval_gate.json"
    if not gate_path.exists():
        return True, f"no approval_gate.json at {gate_path} -- proceeding (nothing to gate on)"
    gate = load_json(gate_path)
    if gate.get("approved") is True:
        return True, "approval gate open (approved: true)"
    if force:
        return True, "approval gate closed but --force-log set -- proceeding anyway"
    return False, "approval gate closed -- flip approved:true in approval_gate.json first"


def build_email_log_entries(sends_log: dict, m2_dir: Path, email_id_map: dict, dry_run: bool, limit=None):
    entries, skipped = [], 0
    now_iso = datetime.now(timezone.utc).isoformat()
    for batch in sends_log.get("batches", []):
        template_file = batch.get("template_file")
        recording_link = extract_recording_link(m2_dir / template_file) if template_file else ""
        subject = batch.get("subject_a", "")
        for send in batch.get("sample_sends", []):
            if limit is not None and len(entries) >= limit:
                return entries, skipped
            email = send.get("message", {}).get("to", "")
            props = {p["name"]: p["value"] for p in send.get("contactProperties", [])}
            contact_id = email if dry_run else email_id_map.get(email)
            if not contact_id:
                skipped += 1
                continue
            body = {
                "properties": {
                    "hs_timestamp": now_iso,
                    "hs_email_direction": "EMAIL",
                    "hs_email_status": "SENT",
                    "hs_email_subject": subject,
                    "hs_email_text": render_email_preview(props, recording_link),
                },
                "associations": [{
                    "to": {"id": contact_id},
                    "types": [{"associationCategory": "HUBSPOT_DEFINED", "associationTypeId": ASSOC_EMAIL_CONTACT_TYPE_ID}],
                }],
            }
            entries.append({"email": email, "body": body})
    return entries, skipped


def run_log_emails(m2_dir: Path, email_id_map: dict, token, dry_run: bool, strict: bool, force: bool, limit):
    sends_log_path = m2_dir / "sends_log.json"
    if not sends_log_path.exists():
        return {"step": "log-emails", "requests": 0, "records": 0, "status": "skipped",
                "note": f"no sends_log.json at {sends_log_path}", "sample": ""}
    allowed, gate_note = check_approval_gate(m2_dir, force)
    if not allowed:
        print(gate_note, file=sys.stderr)
        return {"step": "log-emails", "requests": 0, "records": 0, "status": "skipped", "note": gate_note, "sample": ""}

    sends_log = load_json(sends_log_path)
    entries, skipped = build_email_log_entries(sends_log, m2_dir, email_id_map, dry_run, limit)
    sample_body = truncate_body(entries[0]["body"]) if entries else "(no entries)"
    ok, fail = 0, 0
    for entry in entries:
        if dry_run:
            continue
        status, parsed, err = http_call("POST", "/crm/v3/objects/emails", token, entry["body"])
        if status in (200, 201):
            ok += 1
        else:
            fail += 1
            print(f"[warn] log-emails {entry['email']} -> {status}: {err}", file=sys.stderr)
            if strict:
                raise StepHardFail(f"log-emails hard-failed on {entry['email']}: {status}")
        time.sleep(RATE_LIMIT_SLEEP)
    return {
        "step": "log-emails", "requests": len(entries), "records": len(entries),
        "status": "planned" if dry_run else ("ok" if fail == 0 else ("partial" if ok else "failed")),
        "note": f"skipped_no_contact_id={skipped}; {gate_note}", "sample": sample_body,
    }


