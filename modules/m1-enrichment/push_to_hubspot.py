def build_company_inputs(rows: list, event_tag: str):
    inputs, skipped = [], 0
    for row in rows:
        domain = (row.get("domain") or "").strip()
        if not domain:
            skipped += 1
            continue
        props = {
            "name": row.get("name", ""),
            "domain": domain,
            "numberofemployees": row.get("numemployees", ""),
            "event_tag": event_tag,
        }
        industry_enum = HUBSPOT_INDUSTRY_ENUM.get((row.get("industry") or "").strip().lower())
        if industry_enum:
            props["industry"] = industry_enum
        inputs.append({"idProperty": "domain", "id": domain, "properties": props})
    return inputs, skipped


def build_contact_inputs(rows: list, event_tag: str, owner_map: dict = None, owner_id_by_email: dict = None,
                          event_slug: str = None):
    """owner_map/owner_id_by_email (see resolve_row_owner_id()): when both
    are given, each row's `region` column resolves to a real
    `hubspot_owner_id` on the upsert -- the fictional `hubspot_owner_email`
    stays CSV-only (routing label, never sent to HubSpot). Omitted with a
    counted, stated reason when unresolvable, never invented. event_slug
    (--event-tag CLI flag): sets postevent_event, a property distinct from
    the per-run `event_tag` above -- this one is a stable, human-chosen slug
    so a single portal shared across multiple events stays filterable by
    event. Returns (inputs, skipped, owner_resolved_count, owner_skip_reasons)."""
    owner_map = owner_map or {}
    owner_id_by_email = owner_id_by_email or {}
    inputs, skipped = [], 0
    owner_resolved = 0
    owner_skip_reasons = []
    for row in rows:
        email = (row.get("email") or "").strip()
        if not email:
            skipped += 1
            continue
        props = {
            "email": email,
            "firstname": row.get("firstname", ""),
            "lastname": row.get("lastname", ""),
            "jobtitle": row.get("jobtitle", ""),
            "company": row.get("company", ""),
            "country": row.get("country", ""),
            "icp_tier": row.get("icp_tier", ""),
            "icp_rationale": row.get("icp_rationale", ""),
            "confidence": row.get("confidence", ""),
            "attendance_status": row.get("attendance_status", ""),
            "needs_review": "true" if str(row.get("needs_review", "")).strip().lower() == "true" else "false",
            "event_tag": event_tag,
        }
        if event_slug:
            props["postevent_event"] = event_slug
        lifecycle = normalize_lifecyclestage(row.get("lifecyclestage", ""))
        if lifecycle:
            props["lifecyclestage"] = lifecycle
        owner_id, skip_reason = resolve_row_owner_id(row.get("region", ""), owner_map, owner_id_by_email)
        if owner_id:
            props["hubspot_owner_id"] = owner_id
            owner_resolved += 1
        else:
            owner_skip_reasons.append((email, skip_reason))
        inputs.append({"idProperty": "email", "id": email, "properties": props})
    return inputs, skipped, owner_resolved, owner_skip_reasons


def match_speaker_email(name: str, segment_emails: list) -> str:
    """Joins one data/incoming/speakers.json entry (name/title/company, no
    email) to its address in data/fixtures/segments.json's flat 'speakers'
    email list. Neither file carries a shared id, so the join key is each
    speaker's own "firstname.lastname" localpart (e.g. "Priya Nair" ->
    "priya.nair@..."), matched case-insensitively -- robust to either list
    being reordered, unlike a positional/index join. Identical algorithm to
    enrich.py::load_speakers() (kept as an independent copy, not imported,
    per this repo's per-module HubSpot-code convention -- see
    build_dashboard.py's resolve_hubspot_token() docstring). Returns '' if
    no match."""
    parts = name.strip().split()
    if not parts:
        return ""
    candidate = f"{parts[0]}.{parts[-1]}".lower() if len(parts) >= 2 else parts[0].lower()
    for email in segment_emails:
        if "@" not in email:
            continue
        if email.split("@", 1)[0].lower() == candidate:
            return email
    return ""


def build_speaker_contact_inputs(speakers: list, segment_emails: list, event_tag: str, event_slug: str = None):
    """--include-speakers: upserts data/incoming/speakers.json contacts
    directly, independent of whatever --in's hubspot_contacts.csv contains
    -- a belt-and-suspenders path for when it was generated by an M1 run
    that predates enrich.py's own load_speakers() fold-in (or points at a
    --hubspot-existing fixture without it). Role marking mirrors the exact
    convention enrich.py already established for the same 3 speakers
    (lifecyclestage='evangelist', a standard property already wired through
    normalize_lifecyclestage() below, plus a human-readable role=speaker
    note in the existing custom icp_rationale property) rather than
    inventing a new custom property -- see HUBSPOT_PUSH.md. No
    `hubspot_owner_id` here: speakers.json carries no country/region signal
    to route on, and owner resolution never invents one (see
    resolve_row_owner_id()) -- a speaker upserted via the primary
    hubspot_contacts.csv path (build_contact_inputs(), the default, see
    load_speakers() in enrich.py) DOES get routed normally, since that CSV
    row does carry a real `region`."""
    inputs, skipped = [], 0
    for sp in speakers:
        name = (sp.get("name") or "").strip()
        email = match_speaker_email(name, segment_emails)
        if not email:
            skipped += 1
            print(f"[warn] --include-speakers: no matching email in segments.json for "
                  f"speaker {name!r} -- skipped", file=sys.stderr)
            continue
        parts = name.split()
        firstname = parts[0] if parts else ""
        lastname = " ".join(parts[1:]) if len(parts) > 1 else ""
        title = (sp.get("title") or "").strip()
        company = (sp.get("company") or "").strip()
        props = {
            "email": email,
            "firstname": firstname,
            "lastname": lastname,
            "jobtitle": title,
            "company": company,
            "lifecyclestage": "evangelist",
            "icp_rationale": (
                f"speaker at this event (title={title!r}, company={company!r}) -- role=speaker; "
                "lifecyclestage set to 'evangelist' rather than the attendee rubric, which does "
                "not apply to a speaker."
            ),
            "event_tag": event_tag,
        }
        if event_slug:
            props["postevent_event"] = event_slug
        inputs.append({"idProperty": "email", "id": email, "properties": props})
    return inputs, skipped


def extract_id_map(responses: list, key_property: str) -> dict:
    """Live-mode only: maps domain->companyId / email->contactId from the
    batch/upsert responses (HubSpot echoes idProperty's value back in
    result['properties'])."""
    id_map = {}
    for resp in responses:
        if not resp:
            continue
        for result in resp.get("results", []):
            key_val = (result.get("properties") or {}).get(key_property)
            if key_val and result.get("id"):
                id_map[key_val] = result["id"]
    return id_map


def build_association_inputs(contact_rows: list, domain_id_map: dict, email_id_map: dict, dry_run: bool):
    inputs, skipped = [], 0
    for row in contact_rows:
        email = (row.get("email") or "").strip()
        domain = (row.get("company_domain") or "").strip()
        if not domain:
            skipped += 1
            continue
        if dry_run:
            inputs.append({
                "from": {"id": email, "id_source": "email (placeholder -- real call uses the contact ID returned by contacts_batch upsert)"},
                "to": {"id": domain, "id_source": "domain (placeholder -- real call uses the company ID returned by companies_batch upsert)"},
                "types": [{"associationCategory": "HUBSPOT_DEFINED", "associationTypeId": ASSOC_CONTACT_COMPANY_TYPE_ID}],
            })
            continue
        contact_id, company_id = email_id_map.get(email), domain_id_map.get(domain)
        if not contact_id or not company_id:
            skipped += 1
            continue
        inputs.append({
            "from": {"id": contact_id},
            "to": {"id": company_id},
            "types": [{"associationCategory": "HUBSPOT_DEFINED", "associationTypeId": ASSOC_CONTACT_COMPANY_TYPE_ID}],
        })
    return inputs, skipped


