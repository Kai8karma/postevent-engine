def http_call(method: str, path: str, token: str, body, timeout: int = 30, _retried: bool = False):
    """Returns (status_code_or_None, parsed_json_or_None, error_text).
    Raises AuthError on 401 -- never caught inside a step, only in main()."""
    global NETWORK_CALLS
    NETWORK_CALLS += 1
    url = path if path.startswith("http") else f"{API_BASE}{path}"
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers={
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
    })
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            raw = resp.read()
            return resp.status, (json.loads(raw) if raw else {}), ""
    except urllib.error.HTTPError as e:
        raw = e.read()
        text = raw.decode("utf-8", "replace")
        if e.code == 401:
            raise AuthError(
                f"HubSpot rejected the token (401 Unauthorized) on {method} {path} -- "
                f"check HUBSPOT_TOKEN / {HUBSPOT_ENV_PATH}."
            )
        if e.code == 429 and not _retried:
            try:
                retry_after = float(e.headers.get("Retry-After", "1"))
            except (TypeError, ValueError):
                retry_after = 1.0
            print(f"[warn] 429 rate-limited on {method} {path}; sleeping {retry_after}s, retrying once",
                  file=sys.stderr)
            time.sleep(retry_after)
            return http_call(method, path, token, body, timeout=timeout, _retried=True)
        return e.code, None, text[:300]
    except urllib.error.URLError as e:
        return None, None, str(e)[:300]


def truncate_body(body) -> str:
    text = json.dumps(body)
    return text if len(text) <= BODY_SAMPLE_LIMIT else text[:BODY_SAMPLE_LIMIT] + "...(truncated)"


def chunked(seq, size):
    return [seq[i:i + size] for i in range(0, len(seq), size)]


