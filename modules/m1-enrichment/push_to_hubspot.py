def normalize_lifecyclestage(value: str) -> str:
    """Only send values HubSpot's default property accepts; strip a trailing
    '_pending' (or similar) suffix before checking membership. Returns '' if
    still unresolvable -- caller omits the property rather than send garbage."""
    v = (value or "").strip().lower()
    if v.endswith("_pending"):
        v = v[: -len("_pending")]
    return v if v in ALLOWED_LIFECYCLE else ""


