#!/usr/bin/env python3
"""push_to_hubspot.py -- real HubSpot CRM v3/v4 client for M1/M2 pipeline output.

Reads the same two M1 files documented in README.md (`hubspot_companies.csv`,
`hubspot_contacts.csv`) and, optionally, M2's `sends_log.json` /
`approval_gate.json`, and pushes them to a real HubSpot portal via the CRM
v3/v4 REST API. Mirrors the request shapes already sampled in
`hubspot_upsert_payload.json` (generated by `tools/make_upsert_payload.py`)
so nothing here invents a new contract.

Steps, always run in order unless --dry-run just plans them:
  1. ensure-properties -- create the custom Contact/Company properties this
     pipeline needs (409 "already exists" counts as success).
  2. upsert companies   -- POST .../companies/batch/upsert, idProperty=domain.
  3. upsert contacts    -- POST .../contacts/batch/upsert, idProperty=email.
     --include-speakers appends the 3 data/incoming/speakers.json contacts
     (joined against data/fixtures/segments.json's email list) to this same
     upsert, in case --in's hubspot_contacts.csv was generated by an M1 run
     that predates enrich.py's own load_speakers() fold-in -- see
     build_speaker_contact_inputs() and HUBSPOT_PUSH.md.
  4. associate          -- POST v4 .../associations/contacts/companies/batch/create,
     using the object IDs returned by steps 2-3.
  5. --log-emails       -- log each m2/sends_log.json sample send as a HubSpot
     Email engagement, associated to its contact. Gated on approval_gate.json.
  6. --verify           -- search contacts/companies by event_tag, print counts.

Two lanes:
  - --dry-run: builds every request (method, URL, body) and prints a compact
    plan. urllib.request.urlopen is never called -- see NETWORK_CALLS below.
  - live (default, requires a token): real HTTP calls, 0.15s between batch
    calls, one retry on 429 (Retry-After), 4xx prints + continues unless
    --strict, 401 aborts the whole run immediately (bad token poisons every
    later call).

Token: env HUBSPOT_TOKEN, else KEY=VALUE lines in
~/.config/postevent/hubspot.env (HUBSPOT_TOKEN=...). Never printed.

Stdlib only (argparse, csv, json, os, re, sys, time, urllib.request,
urllib.error, datetime, pathlib).
"""
