def salvage_failed_chunk(step_name: str, endpoint: str, chunk: list, token, chunk_label: str):
    """A HubSpot batch is all-or-nothing: one invalid record 400s the whole
    request and the response carries no ids, so every valid record in that
    chunk silently loses its id too. Observed live -- 3 RFC-2606 `.example`
    speaker addresses (rejected as INVALID_EMAIL) cost the other 35 contacts
    in their chunk their ids, which then skipped 39 email engagements at
    --log-emails time.

    Re-sends the chunk one record at a time so the valid ones still land.
    Returns (responses, rejected) where rejected is a list of
    (record, reason) for genuinely bad records -- surfaced, never silently
    dropped."""
    responses, rejected = [], []
    print(f"[salvage] {step_name} {chunk_label}: re-sending {len(chunk)} record(s) individually "
          f"so valid rows are not lost to the batch rejection", file=sys.stderr)
    for record in chunk:
        status, parsed, err = http_call("POST", endpoint, token, {"inputs": [record]})
        if status in (200, 201):
            responses.append(parsed)
        else:
            ident = (record.get("id")
                     or (record.get("properties") or {}).get("email")
                     or (record.get("properties") or {}).get("domain")
                     or "<unidentified>")
            rejected.append((ident, f"{status}: {str(err)[:160]}"))
        time.sleep(RATE_LIMIT_SLEEP)
    return responses, rejected


def run_batch_step(step_name: str, endpoint: str, chunks: list, token, dry_run: bool, strict: bool):
    """chunks: list of list-of-input-dicts, each already shaped for a
    batch/upsert or batch/create body. Returns
    (ok, fail, sample_body, responses, rejected)."""
    ok, fail = 0, 0
    responses, rejected = [], []
    sample_body = truncate_body({"inputs": chunks[0]}) if chunks else "(no inputs)"
    for i, chunk in enumerate(chunks):
        body = {"inputs": chunk}
        if dry_run:
            continue
        status, parsed, err = http_call("POST", endpoint, token, body)
        if status in (200, 201):
            ok += 1
            responses.append(parsed)
        else:
            fail += 1
            print(f"[warn] {step_name} chunk {i + 1}/{len(chunks)} -> {status}: {err}", file=sys.stderr)
            if strict:
                raise StepHardFail(f"{step_name} hard-failed on chunk {i + 1}/{len(chunks)}: {status}")
            # 4xx means HubSpot rejected the payload, so retrying the same body
            # is pointless -- but the chunk is usually mostly valid. Salvage it
            # record by record. 5xx/network errors are not salvaged here: the
            # whole request is worth retrying, not splitting.
            if 400 <= status < 500 and len(chunk) > 1:
                salvaged, bad = salvage_failed_chunk(
                    step_name, endpoint, chunk, token, f"chunk {i + 1}/{len(chunks)}")
                responses.extend(salvaged)
                rejected.extend(bad)
                if salvaged:
                    print(f"[salvage] {step_name} chunk {i + 1}/{len(chunks)}: recovered "
                          f"{len(salvaged)} of {len(chunk)} record(s); {len(bad)} genuinely rejected",
                          file=sys.stderr)
        time.sleep(RATE_LIMIT_SLEEP)
    return ok, fail, sample_body, responses, rejected


def run_company_sync(company_inputs: list, token, dry_run: bool, strict: bool):
    """HubSpot rejects batch/upsert keyed on `domain` (not a unique-indexed
    property), so companies are synced as search-by-domain -> batch/update
    for matches + batch/create for the rest. Returns (ok, fail, sample_body,
    responses) in the same shape as run_batch_step so the caller and
    extract_id_map() stay unchanged."""
    ok, fail = 0, 0
    responses = []
    sample_body = truncate_body({"inputs": company_inputs[:BATCH_SIZE]}) if company_inputs else "(no inputs)"
    if dry_run:
        return ok, fail, sample_body, responses
    for i, chunk in enumerate(chunked(company_inputs, BATCH_SIZE)):
        domains = [c["id"] for c in chunk]
        search_body = {
            "filterGroups": [{"filters": [{"propertyName": "domain", "operator": "IN", "values": domains}]}],
            "properties": ["domain"], "limit": 100,
        }
        status, parsed, err = http_call("POST", "/crm/v3/objects/companies/search", token, search_body)
        existing = {}
        if status == 200:
            for r in (parsed or {}).get("results", []):
                dom = ((r.get("properties") or {}).get("domain") or "").lower()
                if dom and dom not in existing:
                    existing[dom] = r["id"]
        else:
            print(f"[warn] company search chunk {i + 1} -> {status}: {err}", file=sys.stderr)
        time.sleep(RATE_LIMIT_SLEEP)
        updates = [{"id": existing[c["id"].lower()], "properties": c["properties"]} for c in chunk if c["id"].lower() in existing]
        creates = [{"properties": c["properties"]} for c in chunk if c["id"].lower() not in existing]
        for endpoint, inputs in (("/crm/v3/objects/companies/batch/update", updates),
                                 ("/crm/v3/objects/companies/batch/create", creates)):
            if not inputs:
                continue
            status, parsed, err = http_call("POST", endpoint, token, {"inputs": inputs})
            if status in (200, 201):
                ok += 1
                responses.append(parsed)
            else:
                fail += 1
                print(f"[warn] {endpoint.rsplit('/', 1)[-1]} companies chunk {i + 1} -> {status}: {err}", file=sys.stderr)
                if strict:
                    raise StepHardFail(f"company sync hard-failed on chunk {i + 1}: {status}")
            time.sleep(RATE_LIMIT_SLEEP)
    return ok, fail, sample_body, responses


def run_ensure_properties(token, dry_run: bool, strict: bool):
    props = [("contacts", p) for p in CONTACT_PROPERTIES] + [("companies", p) for p in COMPANY_PROPERTIES]
    ok, fail = 0, 0
    sample_body = truncate_body(props[0][1]) if props else "(none)"
    for obj_type, prop in props:
        path = f"/crm/v3/properties/{obj_type}"
        if dry_run:
            continue
        status, parsed, err = http_call("POST", path, token, prop)
        if status in (200, 201, 409):  # 409 already-exists counts as success
            ok += 1
        else:
            fail += 1
            print(f"[warn] ensure-properties {obj_type}.{prop['name']} -> {status}: {err}", file=sys.stderr)
            if strict:
                raise StepHardFail(f"ensure-properties hard-failed on {obj_type}.{prop['name']}: {status}")
        time.sleep(RATE_LIMIT_SLEEP)
    return {
        "step": "ensure-properties", "requests": len(props), "records": len(props),
        "status": "planned" if dry_run else ("ok" if fail == 0 else ("partial" if ok else "failed")),
        "note": "", "sample": sample_body,
    }


