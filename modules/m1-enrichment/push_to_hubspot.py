def run_verify(event_tag: str, token, dry_run: bool, strict: bool):
    results = {}
    sample_body = ""
    requests = 0
    for obj_type in ("contacts", "companies"):
        path = f"/crm/v3/objects/{obj_type}/search"
        body = {"filterGroups": [{"filters": [{"propertyName": "event_tag", "operator": "EQ", "value": event_tag}]}],
                "limit": 1}
        if not sample_body:
            sample_body = truncate_body(body)
        requests += 1
        if dry_run:
            continue
        status, parsed, err = http_call("POST", path, token, body)
        if status in (200, 201) and parsed is not None:
            results[obj_type] = parsed.get("total")
        else:
            print(f"[warn] verify {obj_type} search -> {status}: {err}", file=sys.stderr)
            if strict:
                raise StepHardFail(f"verify hard-failed on {obj_type}: {status}")
        time.sleep(RATE_LIMIT_SLEEP)
    # emails have no event_tag property (no per-object custom property step
    # for it) -- fall back to an unfiltered first-page sample, per spec.
    requests += 1
    if not dry_run:
        status, parsed, err = http_call("GET", "/crm/v3/objects/emails?limit=100", token, None)
        if status in (200, 201) and parsed is not None:
            results["emails_sampled_first_page"] = len(parsed.get("results", []))
        else:
            print(f"[warn] verify emails -> {status}: {err}", file=sys.stderr)
            if strict:
                raise StepHardFail(f"verify hard-failed on emails: {status}")
        time.sleep(RATE_LIMIT_SLEEP)
    note = (f"contacts={results.get('contacts', '?')} companies={results.get('companies', '?')} "
            f"emails_sampled_first_page={results.get('emails_sampled_first_page', '?')} "
            f"(event_tag={event_tag}; emails has no event_tag property, unfiltered sample not a filtered total)")
    return {
        "step": "verify", "requests": requests, "records": sum(v for v in results.values() if isinstance(v, int)),
        "status": "planned" if dry_run else "ok", "note": note, "sample": sample_body,
    }


