class AuthError(RuntimeError):
    """401 from HubSpot -- the token is bad; abort the whole run immediately
    rather than burning the remaining requests on a token that will never work."""


class StepHardFail(RuntimeError):
    """--strict: any non-2xx/409 aborts the run instead of continuing."""


