def fetch_portal_id(token, dry_run: bool):
    """GET /account-info/v3/details -> portalId. Only called live (not under
    --dry-run) so --dry-run keeps its zero-network-calls guarantee -- unlike
    owner resolution, this is a new lookup this flag introduces, not a
    pre-existing exception to preserve. Never fatal: a portal_id lookup
    failure must not break the receipt it's labelling."""
    if dry_run or not token:
        return None
    status, parsed, err = http_call("GET", "/account-info/v3/details", token, None)
    if status == 200 and isinstance(parsed, dict):
        return parsed.get("portalId")
    print(f"[warn] could not resolve portal_id -> {status}: {err}", file=sys.stderr)
    return None


def build_receipt(receipts: list, portal_id, dry_run: bool) -> dict:
    """Assembles the --receipt JSON from the same receipts list
    print_receipts() already prints -- each entry gets a 'seconds' key
    stamped at its call site in main() (added, not recomputed, here)."""
    def stage_entry(r):
        ok = r["status"] in ("ok", "planned")
        errors = [] if ok else [r.get("note") or f"{r['step']} status={r['status']}"]
        return {"stage": r["step"], "count": r["records"], "ok": ok, "errors": errors,
                "seconds": round(r.get("seconds", 0.0), 3)}

    stages = [stage_entry(r) for r in receipts]
    by_step = {r["step"]: r for r in receipts}
    verify_receipt = by_step.get("verify")
    return {
        "portal_id": portal_id,
        "stages": stages,
        "contacts_upserted": by_step.get("upsert-contacts", {}).get("records", 0),
        "companies_upserted": by_step.get("upsert-companies", {}).get("records", 0),
        "associations": by_step.get("associate", {}).get("records", 0),
        "verify": ({"status": verify_receipt["status"], "note": verify_receipt["note"]}
                   if verify_receipt else {"status": "not_run", "note": "--verify not passed"}),
        "ts": datetime.now(timezone.utc).isoformat(),
    }


def write_receipt_file(receipt_path: str, receipts: list, token, dry_run: bool):
    portal_id = fetch_portal_id(token, dry_run)
    receipt = build_receipt(receipts, portal_id, dry_run)
    path = Path(receipt_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(receipt, indent=2), encoding="utf-8")
    print(f"receipt written: {path}")


