def resolve_token():
    token = os.environ.get("HUBSPOT_TOKEN")
    if token:
        return token.strip()
    if HUBSPOT_ENV_PATH.exists():
        for line in HUBSPOT_ENV_PATH.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            if key.strip() == "HUBSPOT_TOKEN":
                return value.strip().strip('"').strip("'")
    return None


def slugify(name: str) -> str:
    """Identical to orchestrator/run_pipeline.py::slugify -- do not let the
    two drift, or --in's default will look in the wrong out/ dir."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.strip().lower()).strip("-")
    return slug or "event"


def event_slug_for(event_dir: Path) -> str:
    """Identical to orchestrator/run_pipeline.py::event_slug_for."""
    event_path = event_dir / "event.json"
    try:
        event = json.loads(event_path.read_text(encoding="utf-8"))
        return slugify(event.get("event_name", "event"))
    except (OSError, json.JSONDecodeError):
        return "event"


def resolve_event_tag(in_dir: Path) -> str:
    """Prefer M3's manifest.json (already computed for this exact run via
    modules/m3-repurpose/repurpose.py::event_tag -- `{host_domain}-{date}`);
    fall back to recomputing that same formula from data/incoming/event.json
    if M3 hasn't run yet; last resort is the pipeline dir's own slug."""
    m3_manifest = in_dir / "m3" / "manifest.json"
    if m3_manifest.exists():
        try:
            data = json.loads(m3_manifest.read_text(encoding="utf-8"))
            if data.get("event_tag"):
                return data["event_tag"]
        except json.JSONDecodeError:
            pass
    event_path = DEFAULT_EVENT_DIR / "event.json"
    if event_path.exists():
        try:
            event = json.loads(event_path.read_text(encoding="utf-8"))
            domain = event.get("host_domain", "event").split(".")[0]
            date = event.get("date", "")
            tag = f"{domain}-{date}".strip("-")
            if tag:
                return tag
        except json.JSONDecodeError:
            pass
    return in_dir.name


