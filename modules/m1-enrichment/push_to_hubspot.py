def print_receipts(receipts: list, dry_run: bool):
    for r in receipts:
        line = f"{r['step']} | requests={r['requests']} | records={r['records']} | status={r['status']}"
        if r.get("note"):
            line += f" | {r['note']}"
        print(line)
        if dry_run and r.get("sample"):
            print(f"  sample body: {r['sample']}")
    if dry_run:
        print(f"[dry-run] network_calls_made={NETWORK_CALLS} (urllib.request.urlopen never invoked)")


def main():
    parser = argparse.ArgumentParser(description="Push M1/M2 pipeline output to HubSpot CRM v3/v4.")
    parser.add_argument("--in", dest="in_path", default=None,
                         help="Pipeline out dir (default: out/<slug>, computed the same way "
                              "orchestrator/run_pipeline.py computes its default --out).")
    parser.add_argument("--dry-run", action="store_true", dest="dry_run",
                         help="Build every request and print a compact plan. Zero network calls.")
    parser.add_argument("--limit", type=int, default=None,
                         help="Cap company/contact rows processed and email-log entries built (default: all).")
    parser.add_argument("--include-speakers", action="store_true", dest="include_speakers",
                         help="Step 3 extra: upsert data/incoming/speakers.json contacts (joined by "
                              "firstname.lastname localpart to data/fixtures/segments.json's email list) "
                              "alongside --in's hubspot_contacts.csv rows. Zero network in --dry-run. See "
                              "build_speaker_contact_inputs() and HUBSPOT_PUSH.md.")
    parser.add_argument("--log-emails", action="store_true", dest="log_emails",
                         help="Step 5: log m2/sends_log.json sample sends as HubSpot Email engagements.")
    parser.add_argument("--force-log", action="store_true", dest="force_log",
                         help="Log emails even if approval_gate.json's approved is false.")
    parser.add_argument("--verify", action="store_true",
                         help="Step 6: search HubSpot by event_tag and print counts.")
    parser.add_argument("--strict", action="store_true",
                         help="Abort the whole run on the first non-2xx/409 instead of continuing.")
    args = parser.parse_args()

    in_dir = Path(args.in_path) if args.in_path else (REPO_ROOT / "out" / event_slug_for(DEFAULT_EVENT_DIR))
    m1_dir, m2_dir = in_dir / "m1", in_dir / "m2"
    companies_csv, contacts_csv = m1_dir / "hubspot_companies.csv", m1_dir / "hubspot_contacts.csv"

    for label, p in (("hubspot_companies.csv", companies_csv), ("hubspot_contacts.csv", contacts_csv)):
        if not p.exists():
            print(f"error: {label} not found at {p} -- run orchestrator/run_pipeline.py first, or pass --in",
                  file=sys.stderr)
            sys.exit(1)

    token = None
    if not args.dry_run:
        token = resolve_token()
        if not token:
            print(f"error: no HubSpot token found -- set HUBSPOT_TOKEN or write {HUBSPOT_ENV_PATH} "
                  "(KEY=VALUE lines, HUBSPOT_TOKEN=...). Use --dry-run to preview without one.", file=sys.stderr)
            sys.exit(1)

    event_tag = resolve_event_tag(in_dir)
    company_rows, contact_rows = load_csv(companies_csv), load_csv(contacts_csv)
    if args.limit is not None:
        company_rows, contact_rows = company_rows[:args.limit], contact_rows[:args.limit]

    receipts = []
    exit_code = 0

    try:
        # Step 1: ensure-properties
        receipts.append(run_ensure_properties(token, args.dry_run, args.strict))

        # Step 2: upsert companies
        company_inputs, company_skipped = build_company_inputs(company_rows, event_tag)
        company_chunks = chunked(company_inputs, BATCH_SIZE)
        c_ok, c_fail, c_sample, company_responses = run_company_sync(
            company_inputs, token, args.dry_run, args.strict)
        receipts.append({
            "step": "upsert-companies", "requests": len(company_chunks), "records": len(company_inputs),
            "status": "planned" if args.dry_run else ("ok" if c_fail == 0 else ("partial" if c_ok else "failed")),
            "note": f"skipped_no_domain={company_skipped}", "sample": c_sample,
        })

        # Step 3: upsert contacts
        print("note: hubspot_owner_email / hubspot_owner_id routing is emitted in the CSV but NOT pushed "
              "to HubSpot in this sandbox pass (no matching owners) -- see HUBSPOT_PUSH.md.")
        contact_inputs, contact_skipped = build_contact_inputs(contact_rows, event_tag)
        speaker_upserted, speaker_skipped = 0, 0
        if args.include_speakers:
            if DEFAULT_SPEAKERS_PATH.exists():
                speakers_data = load_json(DEFAULT_SPEAKERS_PATH)
                segment_emails = (load_json(DEFAULT_SEGMENTS_PATH).get("speakers", [])
                                   if DEFAULT_SEGMENTS_PATH.exists() else [])
                speaker_inputs, speaker_skipped = build_speaker_contact_inputs(
                    speakers_data, segment_emails, event_tag)
                contact_inputs.extend(speaker_inputs)
                speaker_upserted = len(speaker_inputs)
            else:
                print(f"[warn] --include-speakers: no speakers.json at {DEFAULT_SPEAKERS_PATH} -- skipping",
                      file=sys.stderr)
        contact_chunks = chunked(contact_inputs, BATCH_SIZE)
        k_ok, k_fail, k_sample, contact_responses, contact_rejected = run_batch_step(
            "upsert-contacts", "/crm/v3/objects/contacts/batch/upsert", contact_chunks, token, args.dry_run, args.strict)
        contact_note = f"skipped_no_email={contact_skipped}"
        if args.include_speakers:
            contact_note += f"; speakers_included={speaker_upserted} speakers_skipped_no_match={speaker_skipped}"
        if contact_rejected:
            contact_note += f"; rejected_by_hubspot={len(contact_rejected)}"
            print(f"[warn] upsert-contacts: {len(contact_rejected)} record(s) rejected by HubSpot after "
                  f"individual retry -- these have no contact id, so any email engagement for them "
                  f"cannot be logged:", file=sys.stderr)
            for ident, reason in contact_rejected:
                print(f"       {ident} -> {reason}", file=sys.stderr)
        receipts.append({
            "step": "upsert-contacts", "requests": len(contact_chunks), "records": len(contact_inputs),
            "status": "planned" if args.dry_run else ("ok" if (k_fail == 0 and not contact_rejected)
                                                       else ("partial" if (k_ok or contact_responses) else "failed")),
            "note": contact_note, "sample": k_sample,
        })

        # Step 4: associate
        domain_id_map = {} if args.dry_run else extract_id_map(company_responses, "domain")
        email_id_map = {} if args.dry_run else extract_id_map(contact_responses, "email")
        assoc_inputs, assoc_skipped = build_association_inputs(contact_rows, domain_id_map, email_id_map, args.dry_run)
        assoc_chunks = chunked(assoc_inputs, BATCH_SIZE)
        a_ok, a_fail, a_sample, _, _ = run_batch_step(
            "associate", "/crm/v4/associations/contacts/companies/batch/create", assoc_chunks, token, args.dry_run, args.strict)
        receipts.append({
            "step": "associate", "requests": len(assoc_chunks), "records": len(assoc_inputs),
            "status": "planned" if args.dry_run else ("ok" if a_fail == 0 else ("partial" if a_ok else "failed")),
            "note": f"skipped_no_domain_or_id={assoc_skipped}", "sample": a_sample,
        })

        # Step 5: --log-emails
        if args.log_emails:
            receipts.append(run_log_emails(m2_dir, email_id_map, token, args.dry_run, args.strict,
                                            args.force_log, args.limit))

        # Step 6: --verify
        if args.verify:
            receipts.append(run_verify(event_tag, token, args.dry_run, args.strict))

    except AuthError as e:
        print(f"error: {e}", file=sys.stderr)
        print_receipts(receipts, args.dry_run)
        sys.exit(1)
    except StepHardFail as e:
        print(f"error: {e}", file=sys.stderr)
        exit_code = 1

    print_receipts(receipts, args.dry_run)
    if any(r["status"] == "failed" for r in receipts):
        exit_code = 1
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
